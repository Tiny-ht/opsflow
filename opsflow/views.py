"""Bounded views: project brief, track context, query formatting, drill-down show, and check."""

from __future__ import annotations

import json
from pathlib import Path

from .config import OpsContext
from .storage import atomic_text, now_iso, sha256_file
from .tracks import get_track, list_tracks


def json_text(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(",", ":")) + "\n"


def fit(text: str, budget: int) -> str:
    if budget < 512:
        raise ValueError("budget must be at least 512 bytes")
    size = len(text.encode("utf-8"))
    if size > budget:
        raise ValueError(
            f"output requires {size} bytes, exceeding the {budget}-byte budget; "
            "paginate or select specific fields instead of truncating conclusions"
        )
    return text


def project(ctx: OpsContext) -> dict:
    path = ctx.project_file
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"{path} must contain a JSON object")
    for field in ("baseline", "constraints", "evidence_refs"):
        items = value.get(field)
        if not isinstance(items, list) or any(not isinstance(v, str) for v in items):
            raise ValueError(f"{path} field {field!r} must be a list of strings")
    return value


def brief(ctx: OpsContext, budget: int | None = None, write: bool = False) -> str:
    limit = ctx.budget("brief_bytes") if budget is None else budget
    info = project(ctx)
    cards = list_tracks(ctx)
    order = {"active": 0, "paused": 1, "planned": 2}
    current = sorted((c for c in cards if c["status"] != "closed"), key=lambda c: (order[c["status"]], c["track_id"]))
    lines = [
        f"# {ctx.project_name} Brief",
        "",
        "Generated by `opsflow brief --write`. Update track cards and regenerate instead of editing by hand.",
        "",
        "## Baseline & Boundaries",
        *([f"- {item}" for item in info["baseline"]] or ["- (none)"]),
        "",
        "## Active Constraints",
        *([f"- {item}" for item in info["constraints"]] or ["- (none)"]),
        "",
        "## Open Tracks",
    ]
    if not current:
        lines.append("No open tracks registered. This does not confirm all external or background processes are idle.")
    tail = [
        "",
        f"Registered tracks: {len(cards)}; open: {len(current)}.",
        "Verify live process state via each track's status_refs; reading a file does not prove liveness.",
        "Track context: `opsflow context --track <track_id>`",
        "List tracks:   `opsflow query --source track --status active`",
        "Search ledger: `opsflow query --keyword <topic>`",
    ]
    shown = 0
    for card in current:
        entry = (
            f"- `{card['track_id']}` [{card['status']}] {card['title']} "
            f"(next: {len(card['next_actions'])}, blockers: {len(card['blockers'])})"
        )
        if len(("\n".join(lines + [entry] + tail) + "\n").encode("utf-8")) > limit - 150 or shown >= 20:
            break
        lines.append(entry)
        shown += 1
    if shown < len(current):
        lines.append(f"{len(current) - shown} more open track(s) omitted; use `opsflow query --source track`.")
    text = fit("\n".join(lines + tail) + "\n", limit)
    if write:
        atomic_text(ctx.brief_file, text)
    return text


def observe_status(ctx: OpsContext, reference: str) -> dict:
    path = ctx.resolve_ref(reference)
    item: dict = {
        "path": reference,
        "observed_at": now_iso(ctx.default_timezone()),
        "meaning": "File observation only; does not verify live process health",
    }
    if not path.is_file():
        return dict(item, error="status file is missing or inaccessible")
    stat = path.stat()
    item.update(size_bytes=stat.st_size, mtime_ns=stat.st_mtime_ns)
    if stat.st_size > 256 * 1024:
        return dict(item, note="large status file (>256 KiB) not loaded automatically; inspect source directly")
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(value, dict):
            return dict(item, note="status file is not a JSON object")
        fields = (
            "status", "state", "stage", "phase", "updated_at", "ts", "at",
            "completed_at", "finished_at", "enabled", "total", "completed",
            "failed", "running", "pending",
        )
        for name in fields:
            if name in value:
                field = value[name]
                if isinstance(field, (int, float, bool, type(None))):
                    item[name] = field
                elif isinstance(field, str) and len(field) <= 240:
                    item[name] = field
                else:
                    item[name] = {"count": len(field)}
    except (ValueError, OSError) as exc:
        item["error"] = str(exc)
    return item


def context(ctx: OpsContext, track_id: str, budget: int | None = None, as_json: bool = False) -> str:
    limit = ctx.budget("context_bytes") if budget is None else budget
    card = get_track(ctx, track_id)
    lesson_files = (
        [p.relative_to(ctx.ops_dir).as_posix() for p in sorted(ctx.lessons_dir.glob("**/*.md"))]
        if ctx.lessons_dir.is_dir() else []
    )
    value = {
        "project": project(ctx),
        "track": card,
        "observations": [observe_status(ctx, ref) for ref in card["status_refs"]],
        "lessons": lesson_files,
        "read_more": (
            f"opsflow query --track {track_id}; for legacy untagged rows use "
            f"`opsflow query --keyword {track_id}`; expand with `opsflow show <key> --field /<field>`"
        ),
    }
    hint = f"; read fields via `opsflow show {track_id} --field /next_actions` or `opsflow show project`"
    if as_json:
        try:
            return fit(json_text(value), limit)
        except ValueError as exc:
            raise ValueError(f"{exc}{hint}") from exc
    lines = [
        f"# {card['title']}",
        f"Track: {track_id} | Status: {card['status']} | Revision: {card['revision']} | Verified: {card['verified_at'] or 'unverified'}",
        "",
        "## Project Boundaries",
        *[f"- {v}" for v in value["project"]["baseline"] + value["project"]["constraints"]],
    ]
    for label, field in (
        ("Summary", "summary"), ("Conclusion", "conclusion"), ("Next Actions", "next_actions"),
        ("Blockers", "blockers"), ("Track Constraints", "constraints"), ("Evidence Refs", "evidence_refs"),
    ):
        lines.extend(["", f"## {label}"])
        content = card[field]
        lines.extend([f"- {v}" for v in content] if isinstance(content, list) else [content or "(empty)"])
    lines.extend([
        "", "## Local Status Observations", json_text(value["observations"]).rstrip(),
        "", "Lessons on demand: " + (", ".join(value["lessons"]) or "(none)"), value["read_more"],
    ])
    try:
        return fit("\n".join(lines) + "\n", limit)
    except ValueError as exc:
        raise ValueError(f"{exc}{hint}") from exc


def query_output(
    result: dict,
    budget: int = 8 * 1024,
    as_json: bool = False,
    offset: int | None = None,
) -> str:
    offset = result.get("offset", 0) if offset is None else offset
    rows = result["records"]
    for count in range(len(rows), -1, -1):
        next_offset = offset + count if offset + count < result["total"] else None
        value = {
            "records": rows[:count],
            "total": result["total"],
            "next_offset": next_offset,
            "error_count": result.get("error_count", 0),
            "errors": result.get("errors", [])[:2],
        }
        if as_json:
            text = json_text(value)
        else:
            lines = [
                f"{r['key']} | {r.get('time') or 'unknown_time'} | {r['source']} | "
                f"{r.get('title', '')} | {r.get('summary', '')} | {r.get('read_bytes', 0)} bytes"
                for r in rows[:count]
            ]
            lines.append(
                f"Total: {result['total']}, shown: {count}, next_offset={next_offset}. "
                "Use `opsflow show <key>` to expand."
            )
            if value["error_count"]:
                lines.append(f"Index parse errors: {value['error_count']} (run `opsflow check`; excluded from hits).")
            text = "\n".join(lines) + "\n"
        if len(text.encode("utf-8")) <= budget:
            if rows and count == 0:
                raise ValueError("budget is too small to display even one summary card; increase --budget-bytes")
            return fit(text, budget)
    raise ValueError("query metadata exceeds budget; increase --budget-bytes")


def _pointer(value: object, pointer: str) -> object:
    if pointer == "":
        return value
    if not pointer.startswith("/"):
        raise ValueError("--field must be a JSON Pointer, e.g. /metrics/accuracy/value")
    for raw_key in pointer[1:].split("/"):
        key = raw_key.replace("~1", "/").replace("~0", "~")
        value = value[int(key)] if isinstance(value, list) else value[key]
    return value


def show(
    ctx: OpsContext,
    key: str,
    fields: list[str] | None = None,
    offset: int = 0,
    limit: int = 20,
    budget: int | None = None,
    detail: bool = False,
) -> str:
    from .index import get_record

    byte_limit = ctx.budget("show_bytes") if budget is None else budget
    if offset < 0 or limit < 1:
        raise ValueError("offset must be non-negative and limit must be positive")
    found = get_record(ctx, key)
    record = found["record"]
    if detail:
        ref = record.get("detail_ref")
        if not isinstance(ref, dict) or not isinstance(ref.get("path"), str) or not isinstance(ref.get("sha256"), str):
            raise ValueError("this record has no externalized detail_ref; omit --detail")
        path = ctx.resolve_detail_ref(ref["path"])
        if sha256_file(path) != ref["sha256"]:
            raise ValueError(f"externalized detail checksum mismatch: {ref['path']}")
        record = json.loads(path.read_text(encoding="utf-8"))
    if fields:
        selected, pagination = {}, {}
        for field in fields:
            value = _pointer(record, field)
            if isinstance(value, dict):
                keys = list(value)
                selected[field] = {k: value[k] for k in keys[offset:offset + limit]}
                pagination[field] = {
                    "total": len(keys),
                    "next_offset": offset + limit if offset + limit < len(keys) else None,
                    "unit": "key",
                }
                if len(json_text(selected[field]).encode("utf-8")) > byte_limit // 2:
                    selected[field] = [
                        {"field": field + "/" + k.replace("~", "~0").replace("/", "~1"), "bytes": len(json_text(value[k]).encode("utf-8"))}
                        for k in keys[offset:offset + limit]
                    ]
                    pagination[field]["note"] = "subfields exceed half budget; showing directory—query a deeper --field"
            elif isinstance(value, (list, str)):
                items = value.splitlines() if isinstance(value, str) else value
                selected[field] = items[offset:offset + limit]
                pagination[field] = {
                    "total": len(items),
                    "next_offset": offset + limit if offset + limit < len(items) else None,
                    "unit": "line" if isinstance(value, str) else "item",
                }
            else:
                selected[field] = value
        return fit(json_text({"meta": found["meta"], "fields": selected, "pagination": pagination}), byte_limit)
    text = json_text({"meta": found["meta"], "record": record})
    if len(text.encode("utf-8")) <= byte_limit:
        return fit(text, byte_limit)
    field_sizes = [
        {"field": "/" + k.replace("~", "~0").replace("/", "~1"), "bytes": len(json_text(v).encode("utf-8"))}
        for k, v in record.items()
    ]
    catalog = {
        "meta": found["meta"],
        "note": "Record exceeds budget; showing field directory, not a summary. Read with --field /<name> (--offset/--limit for lists, dicts, or lines).",
        "fields": field_sizes[offset:offset + limit],
        "total_fields": len(field_sizes),
        "next_offset": offset + limit if offset + limit < len(field_sizes) else None,
    }
    return fit(json_text(catalog), byte_limit)


def check(ctx: OpsContext) -> dict:
    from .index import get_record, reindex

    errors: list[str] = []
    warnings: list[str] = []
    agent_budget = ctx.budget("agent_doc_bytes")
    for name, path in ctx.agent_doc_paths().items():
        if path.is_file():
            size = path.stat().st_size
            if size > agent_budget:
                errors.append(
                    f"startup doc {path} ({name}) is {size} bytes, exceeding {agent_budget}-byte budget; "
                    "move detailed progress or specs to on-demand docs"
                )
    lessons_budget = ctx.budget("lessons_bytes")
    if ctx.lessons_dir.is_dir():
        lesson_bytes = sum(p.stat().st_size for p in ctx.lessons_dir.glob("**/*.md") if p.is_file())
        if lesson_bytes > lessons_budget:
            errors.append(
                f"lessons/ total size is {lesson_bytes} bytes, exceeding {lessons_budget}-byte budget; "
                "merge or retire stale rules instead of appending an incident log"
            )
    for rel, path in ctx.retired_doc_paths():
        if path.exists():
            errors.append(f"retired global doc exists: {rel} ({path})")
    try:
        expected = brief(ctx)
        if not ctx.brief_file.is_file() or ctx.brief_file.read_text(encoding="utf-8") != expected:
            errors.append(f"{ctx.brief_file.name} is missing or stale; run 'opsflow brief --write'")
        for card in list_tracks(ctx):
            for ref in card["status_refs"]:
                if not ctx.resolve_ref(ref).is_file():
                    warnings.append(f"{card['track_id']} status_ref not accessible: {ref}")
            for ref in card["evidence_refs"]:
                if ref.startswith("ledger:"):
                    try:
                        get_record(ctx, ref[len("ledger:"):])
                    except (KeyError, ValueError) as exc:
                        warnings.append(f"{card['track_id']} evidence_ref index lookup: {exc}")
                elif not ref.startswith(("https://", "http://")) and not ctx.resolve_ref(ref).exists():
                    warnings.append(f"{card['track_id']} evidence_ref not accessible: {ref}")
    except (ValueError, OSError, RuntimeError) as exc:
        errors.append(str(exc))
    try:
        index_stats = reindex(ctx)
        if index_stats.get("error_count"):
            errors.append(f"index encountered {index_stats['error_count']} parse error(s)")
    except (ValueError, RuntimeError, OSError) as exc:
        index_stats = {}
        errors.append(str(exc))
    return {"ok": not errors, "errors": errors, "warnings": warnings, "index": index_stats}
